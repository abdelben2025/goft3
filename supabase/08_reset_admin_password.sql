-- استخدمه عندما يؤكد التطبيق أن التحقق يجري عبر السحابة ويُرفض المستخدم.
-- verify_login تُرجع NULL في ثلاث حالات لا تُميّز بينها: لا مستخدم، لا تجزئة،
-- أو كلمة مرور خاطئة. هذا الملف يتجاوز الثلاثة: يكتب تجزئة جديدة مباشرة في
-- T_USER_SECRET للمستخدم الموجَد فعلًا.
--
-- شغّل الاستعلامات بالترتيب 1 → 2 → 3 → 4 واقرأ نتيجة كل واحد.
