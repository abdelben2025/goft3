-- -----------------------------------------------------------------------------
-- 1) أسماء المستخدمين الموجودة فعلًا في السحابة.
--    اقرأ عمود USERNAME وانتبه للمسافات أو لاسم مختلف عن الذي تكتبه.
--    صفر صفوف ⇒ التطبيق مُهيّأ على مشروع آخر غير الذي تنفّذ فيه هذا الاستعلام.
-- -----------------------------------------------------------------------------
SELECT ID_USER, USERNAME, ROLE
  FROM public.T_USER
 ORDER BY ID_USER;

-- -----------------------------------------------------------------------------
-- 2) ضمان وجود حساب admin في السحابة.
--    إن كان الاستعلام 1 أرجع صفر صفوف فالحسابات موجودة محليًا فقط (النسخة
--    السحابية فارغة)، ولا يمكن لأي كلمة مرور أن تنجح قبل إنشاء الصف.
--    التعامل مع وجود/غياب عمود PASSWORD تلقائيًا حسب تنفيذ 05 من عدمه.
-- -----------------------------------------------------------------------------
DO $$
DECLARE
  v_has_pw boolean;
  v_exists boolean;
  v_id     integer;
BEGIN
  SELECT EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_schema = 'public'
       AND table_name   = 'T_USER'
       AND column_name  = 'PASSWORD'
  ) INTO v_has_pw;

  SELECT EXISTS (
    SELECT 1 FROM public.T_USER WHERE lower(btrim(USERNAME)) = 'admin'
  ) INTO v_exists;

  IF v_exists THEN
    RAISE NOTICE 'حساب admin موجود بالفعل — تخطّي الإنشاء.';
    RETURN;
  END IF;

  IF v_has_pw THEN
    INSERT INTO public.T_USER (USERNAME, PASSWORD, ROLE)
    VALUES ('admin', '', 'admin')
    RETURNING ID_USER INTO v_id;
  ELSE
    INSERT INTO public.T_USER (USERNAME, ROLE)
    VALUES ('admin', 'admin')
    RETURNING ID_USER INTO v_id;
  END IF;

  PERFORM public.set_user_password(v_id, 'GOFT3-temp-2026');
  RAISE NOTICE 'أُنشئ حساب admin برقم % بكلمة المرور المؤقتة.', v_id;
END $$;

-- -----------------------------------------------------------------------------
-- 3) تعيين كلمة مرور مؤقتة لحساب admin (سحابةً، بتجزئة bcrypt من القاعدة).
--    يجب أن تُرجع صفًا واحدًا. لا يوجد ⇒ صحّح الاسم في WHERE ليطابق الاستعلام 1.
-- -----------------------------------------------------------------------------
SELECT public.set_user_password(ID_USER, 'GOFT3-temp-2026')
  FROM public.T_USER
 WHERE lower(btrim(USERNAME)) = 'admin';

-- -----------------------------------------------------------------------------
-- 4) إثبات من طرف القاعدة قبل المحاولة في التطبيق.
--    يجب أن يُرجع صفًا يحوي ID_USER و USERNAME و ROLE.
--    صف ⇒ الدخول سينجح في التطبيق بالكلمة المؤقتة.
-- -----------------------------------------------------------------------------
SELECT public.verify_login('admin', 'GOFT3-temp-2026');

