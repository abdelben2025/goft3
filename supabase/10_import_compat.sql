-- =============================================================================
-- GOFT3 — 10: توافق الاستيراد مع أعمدة الهوية (يدعم الاستيراد الكامل)
--
-- المشكلة: كل جدول يستعمل ID_X integer GENERATED ALWAYS AS IDENTITY، وهذا النوع
-- يرفض أي قيمة صريحة من العميل. ملف النسخة الاحتياطية يحمل المعرّفات نفسها
-- (لأن العلاقات بين الجداول تشير إليها)، فيفشل الإدراج بـ:
--
--   ERROR 428C9: cannot insert a non-DEFAULT value into column "ID_..."
--
-- الحل: تحويل الأعمدة من ALWAYS إلى BY DEFAULT. لا يتغير أي سلوك آخر: الإدراج
-- من التطبيق بدون معرّف يبقى يولّد رقمًا تلقائيًا، لكن الإدراج بالمعرّف الصريح
-- (الاستيراد) يصبح مسموحًا فتحفظ العلاقات بين الجداول.
--
-- ⚠ ترتيب التنفيذ:
--   القسم 1 قبل الاستيراد — مرة واحدة.
--   القسم 2 بعد كل استيراد — يدفع العدّادات أمام أكبر معرّف مستورد، وإلا
--   اصطدم الإدراج التالي برقم موجود (duplicate key).
--   القسم 2 آمن للتكرار في أي وقت.
-- =============================================================================


-- =============================================================================
-- القسم 1 — قبل الاستيراد
-- =============================================================================
DO $$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT c.table_name, c.column_name
      FROM information_schema.columns c
      JOIN information_schema.tables t
        ON t.table_schema = c.table_schema
       AND t.table_name   = c.table_name
     WHERE c.table_schema      = 'public'
       AND t.table_type        = 'BASE TABLE'
       AND c.is_identity       = 'YES'
       AND c.identity_generation = 'ALWAYS'
  LOOP
    EXECUTE format(
      'ALTER TABLE public.%I ALTER COLUMN %I SET GENERATED BY DEFAULT',
      r.table_name, r.column_name);
    RAISE NOTICE 'BY DEFAULT ← %.%', r.table_name, r.column_name;
  END LOOP;
END $$;


-- =============================================================================
-- القسم 2 — بعد الاستيراد (آمن للتكرار)
-- =============================================================================
DO $$
DECLARE
  r      record;
  v_seq  text;
  v_max  bigint;
BEGIN
  FOR r IN
    SELECT c.table_name, c.column_name
      FROM information_schema.columns c
      JOIN information_schema.tables t
        ON t.table_schema = c.table_schema
       AND t.table_name   = c.table_name
     WHERE c.table_schema = 'public'
       AND t.table_type   = 'BASE TABLE'
       AND c.is_identity  = 'YES'
  LOOP
    EXECUTE format('SELECT coalesce(max(%I), 0) FROM public.%I', r.column_name, r.table_name)
      INTO v_max;

    IF v_max > 0 THEN
      v_seq := pg_get_serial_sequence(
        format('public.%I', r.table_name),
        format('%I', r.column_name));

      IF v_seq IS NOT NULL THEN
        EXECUTE format('SELECT setval(%L, %s, true)', v_seq, v_max);
        RAISE NOTICE 'setval(% → %)', r.table_name, v_max;
      END IF;
    END IF;
  END LOOP;
END $$;


-- =============================================================================
-- تحقق: كل الأعمدة يجب أن تكون BY DEFAULT بعد القسم 1.
-- =============================================================================
SELECT c.table_name,
       c.column_name,
       c.identity_generation
  FROM information_schema.columns c
  JOIN information_schema.tables t
    ON t.table_schema = c.table_schema
   AND t.table_name   = c.table_name
 WHERE c.table_schema = 'public'
   AND t.table_type   = 'BASE TABLE'
   AND c.is_identity  = 'YES'
 ORDER BY c.table_name;
